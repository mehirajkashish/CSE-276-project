def _clean_pdf_text(raw: str) -> str:
    """Convert Markdown inline LaTeX / Unicode symbols to clean Latin-1 safe text for PDF output."""
    text = raw or ""
    # Strip math delimiters while keeping formula content readable
    text = re.sub(r"\$\$([\s\S]*?)\$\$", lambda m: m.group(1).strip(), text)
    text = re.sub(r"\$([^$\n]+?)\$", lambda m: m.group(1).strip(), text)
    text = re.sub(r"\\\[([\s\S]*?)\\\]", lambda m: m.group(1).strip(), text)
    text = re.sub(r"\\\(([^)\n]+?)\\\)", lambda m: m.group(1).strip(), text)
    text = re.sub(r"\\frac\{([^}]*)\}\{([^}]*)\}", r"(\1)/(\2)", text)
    text = re.sub(r"\\text\{([^}]*)\}", r"\1", text)
    for pat, rep in _SYMBOL_REPLACEMENTS:
        if pat.startswith("\\"):
            text = re.sub(pat, rep, text)
        else:
            text = text.replace(pat, rep)
    # Strip remaining Markdown emphasis markers cleanly
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1 (\2)", text)
    text = text.replace("**", "").replace("__", "").replace("`", "")
    # Encode strictly to latin-1 (drop unsupported emojis cleanly instead of raising UnicodeEncodeError)
    return text.encode("latin-1", "ignore").decode("latin-1")


class _StudyPDF(FPDF):
    def __init__(self, doc_title: str, doc_subtitle: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.doc_title = _clean_pdf_text(doc_title)[:90]
        self.doc_subtitle = _clean_pdf_text(doc_subtitle)[:110]
        self.set_auto_page_break(auto=True, margin=18)
        self.set_margins(15, 16, 15)

    def header(self):
        if self.page_no() == 1:
            return
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(110, 110, 110)
        self.cell(0, 6, f"StudyMind AI  |  {self.doc_title}", align="L", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(225, 225, 225)
        self.line(15, self.get_y(), 195, self.get_y())
        self.ln(3)

    def footer(self):
        self.set_y(-13)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(130, 130, 130)
        self.cell(0, 6, f"Generated by StudyMind AI  |  Page {self.page_no()} / {{nb}}", align="C")


def render_markdown_to_pdf_bytes(
    title: str,
    markdown_text: str,
    subtitle: Optional[str] = None,
) -> bytes:
    """Render structured Study Toolkit Markdown content into downloadable A4 PDF bytes."""
    clean_title = _clean_pdf_text(title or "StudyMind AI Export")
    date_str = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
    clean_sub = _clean_pdf_text(subtitle or f"StudyMind AI Export  |  {date_str}")

    pdf = _StudyPDF(clean_title, clean_sub)
    pdf.alias_nb_pages()
    pdf.add_page()

    # Cover Header Banner
    pdf.set_fill_color(18, 18, 18)
    pdf.rect(15, 15, 180, 22, style="F")
    pdf.set_xy(19, 18.5)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(255, 255, 255)
    pdf.cell(0, 7, clean_title[:75], new_x="LMARGIN", new_y="NEXT")
    pdf.set_x(19)
    pdf.set_font("Helvetica", "", 8.5)
    pdf.set_text_color(200, 200, 200)
    pdf.cell(0, 5, clean_sub, new_x="LMARGIN", new_y="NEXT")
    pdf.set_y(43)

    lines = (markdown_text or "").replace("\r\n", "\n").split("\n")
    in_code_block = False
    code_lines: List[str] = []
    i = 0

    def _flush_code_block():
        if not code_lines:
            return
        pdf.set_fill_color(244, 245, 247)
        pdf.set_draw_color(215, 218, 224)
        pdf.set_font("Courier", "", 8.5)
        pdf.set_text_color(25, 25, 25)
        block_text = "\n".join(code_lines)
        pdf.multi_cell(0, 4.6, block_text, border=1, fill=True, new_x="LMARGIN", new_y="NEXT")
        pdf.ln(3)
        code_lines.clear()

    def _render_table(table_lines: List[str]):
        rows = []
        for idx, raw_line in enumerate(table_lines):
            cells = [c.strip() for c in raw_line.strip().strip("|").split("|")]
            if idx == 1 and all(re.match(r"^:?-{2,}:?$", c) for c in cells if c):
                continue
            rows.append([_clean_pdf_text(c) for c in cells])
        if not rows:
            return
        num_cols = max(len(r) for r in rows)
        col_w = 180.0 / max(1, num_cols)
        for r_idx, row in enumerate(rows):
            padded = row + [""] * (num_cols - len(row))
            is_header = r_idx == 0
            pdf.set_font("Helvetica", "B" if is_header else "", 8.5)
            pdf.set_fill_color(24, 24, 24) if is_header else (
                pdf.set_fill_color(248, 248, 248) if r_idx % 2 == 0 else pdf.set_fill_color(255, 255, 255)
            )
            pdf.set_text_color(255, 255, 255) if is_header else pdf.set_text_color(35, 35, 35)
            pdf.set_draw_color(210, 210, 210)
            y_start = pdf.get_y()
            max_h = 6.0
            # Calculate row height conservatively
            for cell_txt in padded:
                est_lines = max(1, (len(cell_txt) // max(12, int(col_w * 0.45))) + 1)
                max_h = max(max_h, est_lines * 4.5 + 2)
            if y_start + max_h > 275:
                pdf.add_page()
                y_start = pdf.get_y()
            for c_idx, cell_txt in enumerate(padded):
                x_pos = 15 + c_idx * col_w
                pdf.rect(x_pos, y_start, col_w, max_h, style="DF")
                pdf.set_xy(x_pos + 1.5, y_start + 1.2)
                pdf.multi_cell(col_w - 3, 4.2, cell_txt, border=0, align="L")
            pdf.set_y(y_start + max_h)
        pdf.ln(3)

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        if stripped.startswith("```"):
            if in_code_block:
                in_code_block = False
                _flush_code_block()
            else:
                in_code_block = True
            i += 1
            continue

        if in_code_block:
            code_lines.append(line.encode("latin-1", "replace").decode("latin-1"))
            i += 1
            continue

        # Table block detection
        if stripped.startswith("|") and "|" in stripped[1:]:
            t_lines = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                t_lines.append(lines[i])
                i += 1
            _render_table(t_lines)
            continue

        if not stripped:
            pdf.ln(2.5)
            i += 1
            continue

        if stripped in ("---", "***", "___"):
            pdf.set_draw_color(215, 215, 215)
            pdf.line(15, pdf.get_y() + 1, 195, pdf.get_y() + 1)
            pdf.ln(4)
            i += 1
            continue

        if stripped.startswith("# "):
            pdf.ln(2)
            pdf.set_font("Helvetica", "B", 14)
            pdf.set_text_color(15, 15, 15)
            pdf.multi_cell(0, 7, _clean_pdf_text(stripped[2:]), new_x="LMARGIN", new_y="NEXT")
            pdf.set_draw_color(200, 200, 200)
            pdf.line(15, pdf.get_y() + 0.5, 195, pdf.get_y() + 0.5)
            pdf.ln(3)
        elif stripped.startswith("## "):
            pdf.ln(2.5)
            pdf.set_font("Helvetica", "B", 11.5)
            pdf.set_text_color(20, 20, 20)
            pdf.multi_cell(0, 6.2, _clean_pdf_text(stripped[3:]), new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1)
        elif stripped.startswith("### ") or stripped.startswith("#### "):
            content = stripped.lstrip("#").strip()
            pdf.ln(1.5)
            pdf.set_font("Helvetica", "B", 10)
            pdf.set_text_color(40, 40, 40)
            pdf.multi_cell(0, 5.5, _clean_pdf_text(content), new_x="LMARGIN", new_y="NEXT")
            pdf.ln(0.8)
        elif stripped.startswith(">"):
            quote = _clean_pdf_text(stripped.lstrip(">").strip())
            pdf.set_fill_color(245, 245, 245)
            pdf.set_draw_color(180, 180, 180)
            pdf.set_font("Helvetica", "I", 9.5)
            pdf.set_text_color(55, 55, 55)
            pdf.multi_cell(0, 5.2, quote, border="L", fill=True, new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1.8)
        elif re.match(r"^[-*]\s+", stripped):
            item = _clean_pdf_text(re.sub(r"^[-*]\s+", "", stripped))
            pdf.set_font("Helvetica", "", 9.8)
            pdf.set_text_color(35, 35, 35)
            pdf.set_x(19)
            pdf.multi_cell(176, 5.3, f"-  {item}", new_x="LMARGIN", new_y="NEXT")
            pdf.ln(0.6)
        elif re.match(r"^\d+\.\s+", stripped):
            pdf.set_font("Helvetica", "", 9.8)
            pdf.set_text_color(35, 35, 35)
            pdf.set_x(19)
            pdf.multi_cell(176, 5.3, _clean_pdf_text(stripped), new_x="LMARGIN", new_y="NEXT")
            pdf.ln(0.6)
        else:
            pdf.set_font("Helvetica", "", 9.8)
            pdf.set_text_color(35, 35, 35)
            pdf.multi_cell(0, 5.4, _clean_pdf_text(stripped), new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1.2)

        i += 1

    if in_code_block:
        _flush_code_block()

    raw_out = pdf.output()
    return bytes(raw_out)
